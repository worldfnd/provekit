use {
    bn254_multiplier_codegen::{karatsuba, schoolbook, simd},
    hla::builder::{build_includable, Interleaving},
};

fn main() {
    build_includable(
        "./asm/montgomery_interleaved_3.s",
        Interleaving::par(
            Interleaving::single(karatsuba::MUL),
            Interleaving::single(simd::setup_single_step),
        ),
    );
    build_includable(
        "./asm/montgomery_square_interleaved_3.s",
        Interleaving::par(
            Interleaving::single(schoolbook::setup_square_single_step),
            Interleaving::single(simd::setup_square_single_step),
        ),
    );
    build_includable(
        "./asm/montgomery_square_log_interleaved_3.s",
        Interleaving::par(
            Interleaving::single(schoolbook::setup_square_log_jump),
            Interleaving::single(simd::setup_square_single_step),
        ),
    );
    build_includable(
        "./asm/montgomery_interleaved_4.s",
        Interleaving::par(
            Interleaving::seq(vec![
                schoolbook::setup_single_step,
                schoolbook::setup_single_step,
            ]),
            Interleaving::single(simd::setup_single_step),
        ),
    );
    build_includable(
        "./asm/montgomery_square_interleaved_4.s",
        Interleaving::par(
            Interleaving::seq(vec![
                schoolbook::setup_square_single_step,
                schoolbook::setup_square_single_step,
            ]),
            Interleaving::single(simd::setup_square_single_step),
        ),
    );
    build_includable(
        "./asm/montgomery_square_log_interleaved_4.s",
        Interleaving::par(
            Interleaving::seq(vec![
                schoolbook::setup_square_log_jump,
                schoolbook::setup_square_log_jump,
            ]),
            Interleaving::single(simd::setup_square_single_step),
        ),
    );
    build_includable(
        "./asm/montgomery.s",
        Interleaving::single(schoolbook::setup_single_step),
    );
    build_includable(
        "./asm/montgomery_square.s",
        Interleaving::single(schoolbook::setup_square_single_step),
    );
    build_includable(
        "./asm/montgomery_log_jump.s",
        Interleaving::single(schoolbook::setup_log_jump),
    );
    build_includable(
        "./asm/montgomery_mul.s",
        Interleaving::single(karatsuba::MUL),
    );
}
